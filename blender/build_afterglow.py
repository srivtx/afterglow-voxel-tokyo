# Tokyo Tower-inspired lattice landmark
# ----------------------------------------------------------------------------

def build_tokyo_tower(col):
    tx, ty = 26.0, 95.0
    H = 62.0
    parts = []
    steel = MATS["AG_SteelPainted"]
    glow = MATS["AG_TowerGlow"]
    beam = MATS["AG_TowerBeam"]

    def half_width(z):
        t = z / H
        if t < 0.42:
            return 5.6 * (1.0 - 0.30 * (t / 0.42))
        if t < 0.62:
            return 3.9 * (1.0 - 0.22 * ((t - 0.42) / 0.20))
        return 3.0 * max(0.06, 1.0 - (t - 0.62) / 0.38) ** 1.25

    steps = 15
    zs = [H * i / steps for i in range(steps + 1)]
    for i in range(steps):
        z0, z1 = zs[i], zs[i + 1]
        zc = (z0 + z1) / 2
        h0, h1 = half_width(z0), half_width(z1)
        seg_h = z1 - z0

        # four corner legs
        for (sx, sy) in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
            x0 = tx + sx * h0
            y0 = ty + sy * h0
            x1 = tx + sx * h1
            y1 = ty + sy * h1
            d = Vector((x1 - x0, y1 - y0, seg_h))
            leg = cyl(f"Tower_Leg_{i}_{sx}{sy}", (0, 0, 0), 0.26, d.length * 1.05,
                      steel, col, verts=6)
            leg.location = (x0 + d.x / 2, y0 + d.y / 2, z0 + d.z / 2)
            leg.rotation_euler = d.to_track_quat('Z', 'Y').to_euler()
            parts.append(leg)

        # horizontal ring beams
        ring = cube(f"Tower_Ring_{i}", (tx, ty, z0), (h0 * 2, h0 * 2, 0.16), steel, col)
        parts.append(ring)

        # X bracing on each of the 4 faces
        for (ax, ay) in ((0, -1), (1, 0), (0, 1), (-1, 0)):
            span = h0 * 2
            diag = math.hypot(span, seg_h)
            for s in (-1, 1):
                br = cube(f"Tower_Brace_{i}_{ax}{ay}_{s}", (0, 0, 0),
                          (diag, 0.11, 0.11), steel, col)
                ang = math.atan2(seg_h, span)
                mid = Vector((tx + ax * h0, ty + ay * h0, zc))
                br.location = mid
                if ax == 0:
                    br.rotation_euler = (0, s * ang, 0)
                else:
                    br.rotation_euler = (s * ang, 0, 0)
                parts.append(br)

    # observation decks
    for (dz, hw, name) in ((0.42, 4.4, "Deck1"), (0.62, 3.2, "Deck2")):
        z = H * dz
        parts.append(cube(f"Tower_{name}", (tx, ty, z), (hw * 2, hw * 2, 1.5), steel, col))
        parts.append(cube(f"Tower_{name}_Glow", (tx, ty, z), (hw * 2 - 0.5, hw * 2 - 0.5, 0.9),
                          glow, col))

    # main illumination bands (the tower's signature orange lighting)
    for z, hh in ((H * 0.50, 1.1), (H * 0.72, 0.8), (H * 0.88, 0.55)):
        parts.append(cube(f"Tower_Band_{int(z)}", (tx, ty, z), (2.3, 2.3, hh), glow, col))

    # antenna mast
    parts.append(cyl("Tower_Mast", (tx, ty, H + 5.0), 0.20, 10.0, steel, col, verts=8))
    for i in range(4):
        parts.append(cyl(f"Tower_MastRing_{i}", (tx, ty, H + 1.4 + i * 2.3),
                         0.42 - i * 0.07, 0.22, glow, col, verts=8))
    parts.append(ico("Tower_Beacon", (tx, ty, H + 10.2), 0.34, beam, col, subdiv=2))

    # glow light so it bleeds warm light onto nearby haze
    lp = bpy.data.lights.new("Tower_GlowLight", 'POINT')
    lp.energy = 4200
    lp.color = (1.0, 0.46, 0.20)
    lp.shadow_soft_size = 8.0
    lo = bpy.data.objects.new("Tower_GlowLight", lp)
    lo.location = (tx, ty, H * 0.55)
    bpy.context.scene.collection.objects.link(lo)
    link(lo, "LIGHTING")
    return parts


