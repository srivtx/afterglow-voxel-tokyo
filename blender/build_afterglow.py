def _uv_scale_by_size(obj, target=3.0):
    """
    Blender's primitive_cube_add gives every face a 0..1 UV, so a 40 m tower and
    a 2 m shed would show the same texel density. Rescale the UVs so one texture
    tile spans roughly `target` metres on every face, which is what keeps the
    window grid the same physical size across the whole skyline.
    """
    me = obj.data
    if not me.uv_layers:
        return
    uv = me.uv_layers.active.data
    dims = obj.dimensions
    sx = max(1.0, dims.x / target)
    sy = max(1.0, dims.y / target)
    sz = max(1.0, dims.z / target)

    # MeshLoop in 5.x has no .polygon_index, so walk polygons and their loops
    # directly: each polygon tells us its dominant axis once, then we rescale
    # all of its loop UVs together.
    for poly in me.polygons:
        n = poly.normal
        ax = max(range(3), key=lambda i: abs(n[i]))
        if ax == 0:
            su, sv = sy, sz
        elif ax == 1:
            su, sv = sx, sz
        else:
            su, sv = sx, sy
        for li in poly.loop_indices:
            u, v = uv[li].uv
            uv[li].uv = (u * su, v * sv)


def cube(name, loc, size, material=None, col=None, rot=None, uv_scale=True,
         uv_target=3.0):
    bpy.ops.mesh.primitive_cube_add(size=2, location=loc)
    o = bpy.context.active_object
    o.name = name
    o.scale = (size[0] / 2, size[1] / 2, size[2] / 2)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if rot:
        o.rotation_euler = rot
    if uv_scale:
        _uv_scale_by_size(o, uv_target)
    if material:
        o.data.materials.append(material)
    if col:
        link(o, col)
    return o


def cyl(name, loc, radius, depth, material=None, col=None, verts=12, rot=None):
    bpy.ops.mesh.primitive_cylinder_add(vertices=verts, radius=radius,
                                        depth=depth, location=loc)
    o = bpy.context.active_object
    o.name = name
    if rot:
        o.rotation_euler = rot
    if material:
        o.data.materials.append(material)
    if col:
        link(o, col)
    return o


def cone(name, loc, r1, r2, depth, material=None, col=None, verts=4, rot_z=0.0):
    bpy.ops.mesh.primitive_cone_add(vertices=verts, radius1=r1, radius2=r2,
                                    depth=depth, location=loc)
    o = bpy.context.active_object
    o.name = name
    o.rotation_euler[2] = rot_z
    if material:
        o.data.materials.append(material)
    if col:
        link(o, col)
    return o


def ico(name, loc, radius, material=None, col=None, subdiv=2, scale=None):
    bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=subdiv, radius=radius,
                                          location=loc)
    o = bpy.context.active_object
    o.name = name
    if scale:
        o.scale = scale
    if material:
        o.data.materials.append(material)
    if col:
        link(o, col)
    return o


def join(objs, name):
    """Join a list of objects into the first one."""
    objs = [o for o in objs if o]
    if not objs:
        return None
    bpy.ops.object.select_all(action='DESELECT')
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]
    bpy.ops.object.join()
    objs[0].name = name
    return objs[0]


