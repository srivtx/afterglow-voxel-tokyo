def build_sky(col):
    """Inverted sphere with a hand-authored twilight gradient + sun glow."""
    bpy.ops.mesh.primitive_uv_sphere_add(radius=400, segments=48, ring_count=32,
                                         location=(0, 0, 0))
    dome = bpy.context.active_object
    dome.name = "SKY_DOME"
    link(dome, col)

    m = bpy.data.materials.new("AG_SkyDome")
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    emit = nt.nodes.new("ShaderNodeEmission")
    ramp = nt.nodes.new("ShaderNodeValToRGB")
    sep = nt.nodes.new("ShaderNodeSeparateXYZ")
    tex = nt.nodes.new("ShaderNodeTexCoord")
    map_ = nt.nodes.new("ShaderNodeMapping")

    nt.links.new(tex.outputs["Generated"], map_.inputs["Vector"])
    nt.links.new(map_.outputs["Vector"], sep.inputs["Vector"])

    # Z of the generated sphere -> 0 at bottom, 1 at top. Remap to horizon band.
    mr = nt.nodes.new("ShaderNodeMapRange")
    mr.inputs["From Min"].default_value = 0.34
    mr.inputs["From Max"].default_value = 0.72
    nt.links.new(sep.outputs["Z"], mr.inputs["Value"])
    nt.links.new(mr.outputs["Result"], ramp.inputs["Fac"])

    els = ramp.color_ramp.elements
    els[0].position = 0.0
    els[0].color = (0.90, 0.36, 0.20, 1.0)     # warm horizon (sunset)
    els[1].position = 0.30
    els[1].color = (0.78, 0.30, 0.40, 1.0)     # coral
    e = els.new(0.52); e.color = (0.48, 0.20, 0.48, 1.0)   # mauve
    e = els.new(0.72); e.color = (0.20, 0.10, 0.40, 1.0)   # violet
    e = els.new(1.00); e.color = (0.030, 0.030, 0.110, 1.0)  # deep cobalt zenith

    nt.links.new(ramp.outputs["Color"], emit.inputs["Color"])
    emit.inputs["Strength"].default_value = 1.0
    nt.links.new(emit.outputs["Emission"], out.inputs["Surface"])

    dome.data.materials.append(m)
    for p in dome.data.polygons:
        p.use_smooth = True
    return dome


def build_clouds(col):
    """Low-poly cloud banks near the horizon, lit warm from beneath.

    Flat icospheres read as grey slabs, so each blob is squashed on two axes,
    given smooth shading, and split into a warm sunlit underside and a cool
    shadowed top to match a sunset sky.
    """
    rng = random.Random(31)

    def cloud_mat(name, base, emit, emit_col):
        m = bpy.data.materials.new(name)
        m.use_nodes = True
        bsdf = m.node_tree.nodes["Principled BSDF"]
        bsdf.inputs["Base Color"].default_value = (*base, 1.0)
        bsdf.inputs["Roughness"].default_value = 1.0
        bsdf.inputs["Emission Color"].default_value = (*emit_col, 1.0)
        bsdf.inputs["Emission Strength"].default_value = emit
        return m

    # Warm body catches the sunset; the "lit" variant is used for the
    # undersides that face the horizon glow. Emission kept well under 1.0 so
    # they stay translucent-looking instead of blowing out to white.
    warm = cloud_mat("AG_CloudWarm", (0.72, 0.36, 0.38), 0.42, (0.95, 0.44, 0.34))
    lit = cloud_mat("AG_CloudLit", (0.88, 0.55, 0.42), 0.58, (1.0, 0.60, 0.38))
    shade = cloud_mat("AG_CloudShade", (0.26, 0.18, 0.38), 0.22, (0.38, 0.24, 0.48))

    parts = []
    for i in range(22):
        a = rng.uniform(math.radians(20), math.radians(160))
        dist = rng.uniform(210, 340)
        cx = math.cos(a) * dist
        cy = 40 + math.sin(a) * dist
        # Keep clouds high and tight to the horizon band; low ones drift into
        # frame and read as grey slabs across the skyline.
        cz = rng.uniform(46, 105)
        n = rng.randint(4, 7)
        for k in range(n):
            ox = rng.uniform(-22, 22)
            oy = rng.uniform(-12, 12)
            oz = rng.uniform(-4, 4)
            # Lower blobs catch the warm horizon, upper ones stay in shadow.
            roll = rng.random()
            mm = lit if (oz < 0 and roll > 0.45) else (shade if roll > 0.82 else warm)
            blob = ico(f"Cloud_{i}_{k}", (cx + ox, cy + oy, cz + oz),
                       rng.uniform(9, 20), mm, col, subdiv=2,
                       scale=(1.0, rng.uniform(0.5, 0.8), rng.uniform(0.20, 0.34)))
            for p in blob.data.polygons:
                p.use_smooth = True
            parts.append(blob)
    return parts


def build_petals(col):
    """Drifting petals via a particle system (near) + real instanced meshes (far)."""
    parts = []
    rng = random.Random(97)

    # real geometry petals near the hero camera so they read in the render
    petal_mesh = bpy.data.meshes.new("Petal_Geo")
    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=1, radius=0.13)
    bmesh.ops.scale(bm, verts=bm.verts, vec=(1.0, 0.55, 0.22))
    bm.to_mesh(petal_mesh)
    bm.free()
    petal_mesh.materials.append(MATS["AG_Petal"])

    for i in range(320):
        a = rng.uniform(0, math.tau)
        r = rng.uniform(6, 70)
        o = bpy.data.objects.new(f"Petal_{i}", petal_mesh)
        o.location = (math.cos(a) * r * 0.9 + 5, 8 + math.sin(a) * r * 0.7,
                      rng.uniform(0.5, 34.0))
        o.rotation_euler = (rng.uniform(0, math.tau), rng.uniform(0, math.tau),
                            rng.uniform(0, math.tau))
        s = rng.uniform(0.7, 1.9)
        o.scale = (s, s, s)
        bpy.context.scene.collection.objects.link(o)
        link(o, col)
        parts.append(o)
    return parts


