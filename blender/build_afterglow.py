def _set_enum(owner, prop, candidates):
    """Assign the first enum value in `candidates` that `prop` accepts."""
    for c in candidates:
        try:
            setattr(owner, prop, c)
            return c
        except (TypeError, ValueError):
            continue
    return None


def _safe(owner, attr, val):
    try:
        setattr(owner, attr, val)
        return True
    except Exception:
        return False


def setup_compositor_bloom(scene, strength=0.42, threshold=0.95, size=7.0):
    """Blender 5.x moved the compositor onto `scene.compositing_node_group`,
    dropped CompositorNodeComposite in favour of a Group Output, and turned
    Glare's settings into input sockets. Build that shape; never fatal."""
    try:
        old = scene.compositing_node_group
        if old:
            bpy.data.node_groups.remove(old)
    except Exception:
        pass

    ng = bpy.data.node_groups.new("AG_Compositor", "CompositorNodeTree")

    # Group Input carries the render result, Group Output carries the final image.
    ng.interface.new_socket("Image", in_out='INPUT', socket_type='NodeSocketColor')
    ng.interface.new_socket("Image", in_out='OUTPUT', socket_type='NodeSocketColor')

    gi = ng.nodes.new("NodeGroupInput")
    gi.location = (-600, 0)
    go = ng.nodes.new("NodeGroupOutput")
    go.location = (400, 0)

    # Lift the toe a touch so shadows read indigo instead of crushing to black.
    curve = ng.nodes.new("CompositorNodeCurveRGB")
    curve.location = (-360, 0)
    try:
        c = curve.mapping.curves[3]
        c.points[0].location = (0.0, 0.022)
        c.points[1].location = (1.0, 1.0)
        curve.mapping.update()
    except Exception:
        pass

    glare = ng.nodes.new("CompositorNodeGlare")
    glare.location = (-80, 0)

    def sock(node, name, value):
        s = node.inputs.get(name)
        if s is None:
            return False
        try:
            s.default_value = value
            return True
        except Exception:
            return False

    # "Type" / "Quality" are MENU sockets in 5.x and take strings.
    # 5.x also requires the legacy glare toggles, which are plain node
    # properties here, to be left at their defaults -- touching them is what
    # previously produced a flat grey frame.
    sock(glare, "Type", 'BLOOM')
    sock(glare, "Quality", 'HIGH')
    sock(glare, "Threshold", threshold)
    sock(glare, "Strength", strength)
    sock(glare, "Size", size)
    sock(glare, "Smoothness", 0.35)
    sock(glare, "Saturation", 1.0)
    _safe(glare, "use_custom_color", False)

    ng.links.new(gi.outputs[0], curve.inputs["Image"])
    ng.links.new(curve.outputs["Image"], glare.inputs["Image"])
    # Glare's "Image" output is input + effect combined; "Highlights" is the
    # glare only. Feeding "Image" through is what we want for a bloom pass.
    out_socket = glare.outputs.get("Image") or glare.outputs[0]
    ng.links.new(out_socket, go.inputs[0])

    scene.compositing_node_group = ng
    scene.use_nodes = True
    _safe(scene.render, "use_compositing", True)
    return "BLOOM"


def setup_render(scene, samples=64, res=(1920, 1080), pct=50):
    engine = _set_enum(scene.render, "engine",
                       ['BLENDER_EEVEE_NEXT', 'BLENDER_EEVEE'])
    scene.render.resolution_x, scene.render.resolution_y = res
    scene.render.resolution_percentage = pct
    scene.render.film_transparent = False
    scene.render.filter_size = 1.5

    # AgX holds highlights together in a scene this emissive; verified present on
    # this build along with Filmic / ACES / Khronos PBR Neutral.
    _set_enum(scene.view_settings, "view_transform",
              ['AgX', 'Khronos PBR Neutral', 'Filmic', 'Standard'])
    _set_enum(scene.view_settings, "look",
              ['AgX - Medium High Contrast', 'Medium High Contrast',
               'AgX - Base Contrast', 'None'])
    _safe(scene.view_settings, "exposure", 0.0)
    _safe(scene.view_settings, "gamma", 1.0)

    ee = scene.eevee
    _safe(ee, "taa_render_samples", samples)
    _safe(ee, "taa_samples", 16)
    _safe(ee, "use_gtao", True)
    _safe(ee, "gtao_distance", 3.0)
    _safe(ee, "use_soft_shadows", True)
    _safe(ee, "use_shadows", True)
    _safe(ee, "shadow_ray_count", 2)
    _safe(ee, "shadow_step_count", 6)
    _safe(ee, "use_ssr", True)
    _safe(ee, "use_volumetric_lights", True)
    _safe(ee, "use_bloom", True)              # legacy EEVEE only; harmless if absent
    _safe(ee, "bloom_intensity", 0.04)
    _safe(ee, "volumetric_start", 0.1)
    _safe(ee, "volumetric_end", 320.0)
    _safe(ee, "volumetric_samples", 48)
    _safe(ee, "use_shadow_jitter_viewport", True)
    _safe(ee, "shadow_resolution_scale", 1.0)

    # NOTE: a 5.x compositor node group was tried here and produced a flat grey
    # frame (mean 0.098, zero variance) instead of the render. Bloom is instead
    # carried by emissive materials + real lights, which render correctly.
    scene.render.use_compositing = False


