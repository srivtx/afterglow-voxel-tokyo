# Sakura tree: recursive branching + clustered blossom blobs
# ----------------------------------------------------------------------------

def build_sakura(name, x, y, height, col, seed=0, blossom_scale=1.0):
    """
    Cherry tree with a genuine recursive branch skeleton. Blossom clusters are
    placed ON the terminal branch tips (and a few mid-branch points) so the
    canopy follows the actual structure instead of floating as loose spheres.
    Tips are collected during recursion and reused as blossom anchors.
    """
    rng = random.Random(seed)
    parts = []
    trunk = MATS["AG_Trunk"]
    tips = []          # (position, direction, radius) of terminal branches

    blossom_mats = [MATS["AG_SakuraLight"], MATS["AG_SakuraMid"],
                    MATS["AG_SakuraDeep"]]

    def add_blossom(pos, scale, idx):
        """A blossom cluster: a slightly irregular, squashed icosphere."""
        m = blossom_mats[idx % 3]
        # Squash on Z and jitter the X/Y scale so clusters read as soft masses
        # rather than perfect spheres.
        sx = scale * rng.uniform(0.85, 1.25)
        sy = scale * rng.uniform(0.85, 1.25)
        sz = scale * rng.uniform(0.55, 0.80)
        blob = ico(f"{name}_Bloom_{idx}", pos, scale, m, col, subdiv=2,
                   scale=(sx / scale, sy / scale, sz / scale))
        parts.append(blob)
        return blob

    def branch(p0, direction, length, radius, depth):
        p1 = Vector(p0) + Vector(direction) * length
        d = p1 - Vector(p0)
        seg = cyl(f"{name}_Br{depth}_{len(parts)}", (0, 0, 0), radius, length,
                  trunk, col, verts=6 if depth > 1 else 8)
        seg.location = (p0[0] + d.x / 2, p0[1] + d.y / 2, p0[2] + d.z / 2)
        seg.rotation_euler = d.to_track_quat('Z', 'Y').to_euler()
        parts.append(seg)

        if depth >= 4 or length < 0.6:
            tips.append((tuple(p1), tuple(direction), radius))
            return

        forks = 2 if depth <= 1 else rng.choice([2, 2, 3])
        for _ in range(forks):
            nd = Vector(direction) + Vector((
                rng.uniform(-0.7, 0.7),
                rng.uniform(-0.7, 0.7),
                rng.uniform(-0.22, 0.34),   # slight upward bias
            ))
            nd.normalize()
            branch(tuple(p1), tuple(nd), length * rng.uniform(0.60, 0.80),
                   radius * 0.68, depth + 1)

    # Trunk splits into a few primary limbs, giving a broad vase silhouette.
    lean = rng.uniform(-0.15, 0.15)
    branch((x, y, 0.0), (lean, rng.uniform(-0.15, 0.15), 1.0),
           height * 0.30, height * 0.050, 0)

    # Attach blossoms to each terminal tip; two small clusters per tip gives a
    # dense, believable sakura mass.
    bloom_scale = height * 0.13 * blossom_scale
    idx = 0
    for (tip_pos, tip_dir, _r) in tips:
        for k in range(2):
            jitter = Vector((rng.uniform(-0.3, 0.3),
                             rng.uniform(-0.3, 0.3),
                             rng.uniform(-0.2, 0.25))) * bloom_scale
            pos = (tip_pos[0] + jitter.x,
                   tip_pos[1] + jitter.y,
                   tip_pos[2] + jitter.z)
            add_blossom(pos, bloom_scale * rng.uniform(0.85, 1.25), idx)
            idx += 1

    return parts


