# Pagoda roof: a curved-eave hip roof built from a lofted mesh.
# Gives the flared, concave silhouette of a real pagoda instead of a cone.
# ----------------------------------------------------------------------------

def pagoda_roof(name, cx, cy, base_z, half_w, height, material, col,
                eave_flare=1.42, curve=0.55, corner_rise=0.30):
    """Layered roof: wide flared eave, concave sweep up to a small finial ridge."""
    rings = 6
    verts, faces = [], []
    for i in range(rings):
        t = i / (rings - 1)              # 0 at eave, 1 at ridge
        # Concave profile: fast pull-in at the top.
        s = (1.0 - t) ** curve
        hw = half_w * eave_flare * s
        z = base_z + height * t
        # Corner tips lift slightly -> reads as upturned eaves.
        corner_lift = corner_rise * (t ** 2)
        for (dx, dy) in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
            verts.append((cx + dx * hw, cy + dy * hw, z + (corner_lift if t > 0.5 else 0)))
        # mid-edge points for a fuller, less diamond-like plan
        for (dx, dy) in ((0, -1), (1, 0), (0, 1), (-1, 0)):
            verts.append((cx + dx * hw * 0.92, cy + dy * hw * 0.92, z + corner_lift * 0.4))

    ring_size = 8
    for i in range(rings - 1):
        for j in range(ring_size):
            a = i * ring_size + j
            b = i * ring_size + (j + 1) % ring_size
            c = (i + 1) * ring_size + (j + 1) % ring_size
            d = (i + 1) * ring_size + j
            faces.append((a, b, c, d))
    faces.append(tuple(range(ring_size)))

    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], faces)
    me.validate()
    me.update()
    o = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(o)
    o.data.materials.append(material)
    link(o, col)
    return o


